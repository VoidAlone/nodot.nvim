-- Run: nvim --headless -u NONE -l tests/integration.lua
vim.opt.rtp:prepend(vim.fn.getcwd())
local base = vim.fn.tempname()
vim.fn.mkdir(base .. '/project', 'p')
vim.fn.writefile({ 'config_version=5', '[application]', 'config/name="nodot test"', '[rendering]', 'renderer/rendering_method="gl_compatibility"' }, base .. '/project/project.godot')
vim.fn.writefile({ 'extends Node', 'func hello() -> int:', '\treturn 42' }, base .. '/project/test.gd')
local nodot = require('nodot')
local function wait_for(predicate, description)
  assert(vim.wait(20000, predicate, 50), 'Timed out: ' .. description .. ' ' .. vim.inspect(nodot.status()))
end
local ok, err = xpcall(function()
  nodot.setup({ lsp_port = 16005, dap_port = 16006, debug_port = 16007 })
  vim.cmd.edit(base .. '/project/test.gd')
  vim.bo.filetype = 'gdscript'
  nodot.start()
  wait_for(function() return nodot.status().state == 'ready' end, 'startup')
  local first_job = nodot.status().job
  nodot.start()
  assert(nodot.status().job == first_job, 'start must be idempotent')
  nodot.connect()
  wait_for(function() return nodot.status().lsp == 'connected' end, 'LSP initialize')
  assert(#vim.lsp.get_clients({ bufnr = 0, name = 'nodot' }) == 1, 'buffer must attach')
  nodot.connect()
  wait_for(function() return nodot.status().lsp == 'connected' end, 'reconnect')
  nodot.restart()
  wait_for(function() return nodot.status().state == 'ready' and nodot.status().lsp == 'connected' end, 'restart and reconnect')
  assert(nodot.status().job ~= first_job)
  nodot.stop()
  assert(nodot.status().state == 'stopped' and nodot.status().lsp == 'disconnected')
  nodot.start()
  nodot.stop()
  vim.wait(500, function() return false end)
  assert(nodot.status().state == 'stopped', 'stop must cancel queued startup')
  -- An occupied port must never become an owned process.
  local listener = vim.uv.new_tcp()
  assert(listener:bind('127.0.0.1', 16005))
  assert(listener:listen(16, function() end))
  nodot.start()
  wait_for(function() return nodot.status().state == 'stopped' end, 'occupied port refusal')
  assert(not nodot.status().owned)
  listener:close()
  print('PASS: startup, idempotence, LSP attach/reconnect, restart, stop, cancellation, occupied port')
end, debug.traceback)
if not ok then nodot.logs(); print(table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), '\n')) end
pcall(nodot.stop)
vim.fn.delete(base, 'rf')
if not ok then error(err) end
